// Console.WriteLine() outputs text to the console. (") for text (;) to end a line of code.
System.Console.WriteLine("Hello, World!"); 

// Join pieces with the '+' operator.
System.Console.WriteLine("Hello," + " " + "World!");

// (\n) Moves text to a new line.
System.Console.WriteLine("Line1\nLine2");

// (\t) Adds a 'TAB-space'.
System.Console.WriteLine("Name:\tMark");

// (\\) Prints a literal 'backslash'.
System.Console.WriteLine("Path: C:\\users");

// (\") Prints a 'double quote'
System.Console.WriteLine("She said, \"Hi!\"");

// Console.Write() doesn't add a 'line break' at the end.
System.Console.Write("Hello, ");
System.Console.Write("");
System.Console.Write("World!");